// Package kbgroup 提供「知识组」键提取与团队档路径判定（单源）。
//
// 案例归档标题行固定为「# 案例 <caseID>：<用户输入>」，同一用户输入的多份案例
// 共享一个知识组。生产实测 4441 份归档仅 259 组、>94% 索引行是重复内容副本——
// 写入侧（飞轮饱和去重）与存量清理侧（bq-kbclean --dedupe）共用本包的键语义：
// 两侧各持一份键逻辑必然漂移，写入侧放行与清理侧漏删互为镜像，重复副本持续
// 膨胀；标题行解析漂移还会让治理台展示的输入与组键对不上。
//
// # 键规则
//
// [KeyFromTitle] 去全部空白并小写归一（「OOM 排查」≡「oom排查」）：中文输入主体
// 无空格语义，空格差异是录入噪声；大小写差异在英文/缩写输入上必须归并。空输入
// 得到空键——调用方须把空键视为「无组」，不得参与饱和判定。
//
// # 团队路径
//
// [TeamSlugOf] 是团队档案路径语义的唯一实现：teams/<slug>/… → slug，其余
// （knowledge 根手册、cases/ 全局归档）返回空。检索按团队过滤、飞轮归档落点、
// 控制台文档清单三处消费；任何一处自写前缀判断，都会在路径形态变化时造成语料
// 跨队泄漏（读到别队语料）或落点错队（写入别队目录）。
//
// # IO 与解析分层
//
// [InputFromDoc] 负责读文件，[InputFromTitleLine] 是纯解析面；调用方已持有标题行
// 时用纯函数，避免同一文件重复打开（5994 案例 × 3 次打开 ≈ 2.7s 的实测教训）。
// 两者共用同一套冒号解析规则：优先取首个全角「：」之后的输入段；无全角冒号时
// 退化尝试半角「: 」（带空格）；都没有则整行视为输入（兼容旧格式）。
