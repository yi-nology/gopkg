// Package webhooksrc 承接通用 webhook 事件源的**五段管道**：鉴权 → 限频 →
// 过滤 → 模板 → 投递（留痕贯穿每一步）。外部系统按「源」接入，每源独立
// 配置鉴权模式、速率、过滤规则、模板；任一拒绝都产出可溯源的原因码。
//
// # 与框架原语的分工
//
// 验签、滑动窗口这类**机制**已有框架件（oekit/pkg/webhook、
// oekit/concurrency/ratelimit）。本仓零第三方依赖，因此本包用 stdlib
// 手写最小实现（HMAC-SHA256 常数时间比对、按源滑动窗口），并在包内把
// 「机制」与「产品语义」分层：
//
//   - 机制层：[VerifyHMAC]、[VerifyBearer]、[Service] 内滑动窗口；
//   - 产品层：按源强制二选一鉴权、过滤算子词表（eq/ne/contains/exists/
//     regex + JSON 点路径）、{{path}} 模板语义（未知路径替换空串）、
//     每步留痕与拒绝原因码。
//
// # 与告警 webhook 的划界
//
// 告警链路（幂等、风暴合并、领域路由）是领域面；本包是**泛化事件源面**，
// 不认会话、不认告警、不内置重试。两者并存，不是替代。
//
// # 宿主注入面
//
// 存储与动作全部接口化，本包不碰数据库、不建会话：
//
//	SourceStore  源配置读取（鉴权/限频/过滤/模板都在 Source 上）
//	EventStore   留痕写入与清扫（表是宿主资产）
//	Sink         第五段动作（宿主接自家会话/队列/事实卡）
//	Snapshot     载荷快照钩子（宿主在此做脱敏；默认截断原文）
//
// 包内提供 [MemorySourceStore]/[MemoryEventStore] 便于测试与单机部署；
// 生产表结构、密钥保管、管理面 CRUD 留宿主。
//
// # 安全边界（如实声明）
//
//   - 载荷快照默认是**请求体原文截断**，不含脱敏。宿主要么注入 Snapshot 做
//     三层脱敏，要么在 EventStore 落库前处理——凭据/手机号可能出现在外部
//     payload 里，这是本包不替宿主做价值判断但必须显式说明的出口。
//   - 限频窗口是**进程内**的：多副本部署时按副本计（与参考实现同边界）。
//   - HMAC 只校验 body，不校验时间戳/nonce；重放防护是宿主的准入面决策。
